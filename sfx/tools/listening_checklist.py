#!/usr/bin/env python3
"""Writes sfx/LISTENING_PASS.md: a by-ear checklist for every sound family and music bed (nothing in the pack has been auditioned yet).
usage: python3 tools/listening_checklist.py     (re-run after a rebuild; ticked boxes are NOT preserved, so copy results into the 'verdicts' table first)"""
import json
import os
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACK = os.path.dirname(HERE)
LISTEN = {
    "indian": "tabla pitch reads as Sa (A); Na rings, Te is dry, Ge glides UP (not down); sitar buzz (jawari) present but not harsh; shehnai / bansuri do not sound like a kazoo; temple bell beats slowly; nothing imitates a known recording",
    "foley": "each take of a footstep differs (play seeds 1-4 back to back); no machine-gun repetition; door / drawer / laptop read as the named object at phone volume",
    "device": "ringtone is original (no famous ringtone contour); keyboard clicks are not too loud under a voice at -20 dB; progress-fill ding lands on the anchor",
    "ui": "voice-assistant set: mic_on rises, mic_off falls, listening loop has no click at the wrap (loop it 4x), think pulse is calm, reply blooms; none resemble an OS assistant chime",
    "crowd": "reads as a crowd reaction, never as words; cheer is not shrill on a phone",
    "ambience": "every loop played 3x in a row: no audible seam, no obvious repeat inside 8 s; thunder / monsoon rumble is not just sub (check on a phone)",
    "impact": "taiko and metal impacts feel big on headphones AND survive on a phone; cymbal swell lands on the crash",
    "riser": "each riser's end lands one frame before the hit in a test mix (mixer.py) and builds steadily",
    "whoosh": "blade / fire / magic / sci-fi whooshes peak at the anchor; no clicks",
    "cartoon": "whistle trill is not painful at -14 LUFS; slip_long thud lands on its anchor",
}
OUT = os.path.join(HERE, "LISTENING_PASS.md")


def main():
    sm = json.load(open(os.path.join(HERE, "manifest.json")))
    mm = json.load(open(os.path.join(PACK, "music", "manifest.json")))
    cats = {}
    for d in sm["sounds"]:
        cats.setdefault(d["category"], []).append(d["id"])
    L = ["# Listening pass (by ear) for motion-pack audio", "",
         "Nothing in `sfx/` or `music/` has been auditioned by a human yet; QA is measurement only. Do this once per family on (1) studio headphones and (2) a phone speaker",
         "at the house master (-14 LUFS-I). Tick a box when the sound passes; write one line per family in the verdicts table; retune recipes that fail and rebuild.",
         "Generated by `tools/listening_checklist.py` from the manifests (%d sounds, %d music items)." % (sm["count"], mm["count"]), "",
         "## How to listen", "```bash",
         "cd sfx && open library/<family>/          # macOS Finder quick-look, space bar plays",
         "afplay library/foley/snd.foley.footstep_wood.wav                                   # or play one file",
         "python3 -c \"import sys; sys.path.insert(0,'.'); import recipes; recipes.load_all(); from mpaudio import registry; import soundfile as sf; [sf.write('/tmp/rr%d.wav' % k, registry.render('snd.foley.footstep_wood', 400 + k)[0], 48000) for k in range(4)]\"   # 4 round-robin takes",
         "```", "", "## Verdicts", "", "| family | headphones | phone | notes / retune |", "|---|---|---|---|"]
    for c in sorted(cats):
        L.append("| %s | | | |" % c)
    L.append("| music beds | | | |")
    for c in sorted(cats):
        L += ["", "## %s (%d)" % (c, len(cats[c]))]
        if c in LISTEN:
            L.append("Listen for: " + LISTEN[c])
        L += ["- [ ] `%s`" % i for i in sorted(cats[c])]
    L += ["", "## music (%d)" % mm["count"], "Listen for: loops wrap cleanly (play twice), the groove sits on the grid, JI presets (indian_fusion, bhangra_hype, raga_calm, festive_dhol) sound in tune against the tanpura, lead does not mask a voice at -10 LU, tempo ramp (bed_anthem_ramp16) accelerates smoothly."]
    L += ["- [ ] `%s` (%s)" % (m["id"], m.get("desc", "")[:90]) for m in mm["items"]]
    open(OUT, "w").write("\n".join(L) + "\n")
    print("wrote", OUT, len(L), "lines")


if __name__ == "__main__":
    main()
