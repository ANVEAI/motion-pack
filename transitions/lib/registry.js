/* motion-pack / transitions / lib / registry.js
   THE source of truth for every transition: params + defaults, beat-grid timing, sound pairing, edit grammar, tags.
   Pure data (no functions) so tools/build.mjs can export it to ../catalog.json for Python planners (cuts/cutgen.py).
   Param types: float | vec2 | vec4 | color ('#rrggbb') | bool | enum (string, sent to GLSL as its index) | text (JS only).
   js: true marks a param consumed by the JS solver (tx-gl.js DERIVE) instead of a GLSL uniform.
   GLSL uniform for param `foo` is `u_foo`. Coordinates in params are normalised, TOP-LEFT origin (designer space).
   timing: ms = free-time default; beats = default length on a beat grid; cut = progress at which the shot swaps
   (the busiest frame of the effect: put it ON the beat); ease = progress curve sent to the shader as uE.
   sfx: ids follow the sound module convention sfx/<category>/<name> (== snd.<category>.<name> in sfx/mpaudio).
   at: where the cue's anchor lands (cut | start | end | peak), offset_f = frames after that point (house rule: +1),
   gain_db = level over the music bed (sound.md 3.x). Reason codes are edit.md section 2. */

