#!/usr/bin/env node
/* motion-pack / transitions / tools / build.mjs
   Registry (lib/registry.js) -> catalog.json (for Python planners / cuts/cutgen.py) + the generated README section.
   usage: node tools/build.mjs [--check]   (--check: exit 1 if catalog.json or README are stale; used by lint) */
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
import { REGISTRY } from '../lib/registry.js';
import { DOM_KEYS, APPROX_KEYS } from '../lib/tx-dom.js';
import { SHADERS } from '../lib/tx-shaders.js';
import { ALIASES, resolveTx } from '../lib/ids.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = p => fs.existsSync(path.join(ROOT, p)) ? p : null;
const frames = (ms, fps) => Math.max(1, Math.round(ms / 1000 * fps));

export function catalog() {
  const transitions = Object.entries(REGISTRY).map(([key, e]) => ({
    key, ...e,
    backends: e.backends, gl: !!SHADERS[key], dom: DOM_KEYS.includes(key), dom_approx: !DOM_KEYS.includes(key) && APPROX_KEYS.includes(key),
    timing: { ...e.timing, frames_30fps: frames(e.timing.ms, 30), frames_24fps: frames(e.timing.ms, 24),
      frames_on_beat: Object.fromEntries([90, 100, 120, 128, 140].map(b => [b, Math.max(e.timing.minFrames || 2, Math.round(e.timing.beats * 60 / b * 30))])) },
    demo: { mp4: rel(`renders/${key}.mp4`), mp4_9x16: rel(`renders/${key}_9x16.mp4`), stills: rel(`renders/stills/${key}`), qa: rel(`renders/qa/${key}.json`) },
  }));
  return { schema: 'motion-pack/transitions@1', note: 'GENERATED by tools/build.mjs from lib/registry.js: edit the registry, not this file',
    sfx_convention: 'sfx/<category>/<name> == snd.<category>.<name> in sfx/mpaudio; anchor lands at (at + offset_f) frames', transitions };
}

function readme(cat) {
  const L = [];
  L.push('| key | id | ms | beats | cut | back-ends | sound (first) | tags |', '|---|---|---|---|---|---|---|---|');
  for (const t of cat.transitions) L.push(`| \`${t.key}\` | ${t.id} | ${t.timing.ms} | ${t.timing.beats} | ${t.timing.cut} | ${[t.gl && 'gl', t.dom && 'dom', t.dom_approx && 'dom~', t.backends.includes('curve') && 'curve'].filter(Boolean).join(' + ')} | \`${t.sfx[0].id}\` | ${t.tags.slice(0, 4).join(', ')} |`);
  L.push('');
  for (const t of cat.transitions) {
    L.push(`### \`${t.key}\` (${t.id}): ${t.name}`, '');
    L.push(`- **Use:** ${t.use}`, `- **Avoid:** ${t.avoid}`, `- **Reasons:** ${t.reasons.join(', ')}. **Tags:** ${t.tags.join(', ')}`);
    L.push(`- **Timing:** ${t.timing.ms} ms free-time (${t.timing.frames_30fps} f @30), ${t.timing.beats} beat(s) on a grid (${t.timing.frames_on_beat[120]} f @120 BPM), swap at p=${t.timing.cut}, ease \`${t.timing.ease}\``);
    L.push(`- **Params:** ` + Object.entries(t.params).map(([k, s]) => `\`${k}\`=${JSON.stringify(s.default)}${s.opts ? ' (' + s.opts.join('|') + ')' : ''}`).join(', '));
    L.push(`- **Sound:** ` + t.sfx.map(s => `\`${s.id}\` at ${s.at}${s.offset_f >= 0 ? '+' : ''}${s.offset_f} f, ${s.gain_db >= 0 ? '+' : ''}${s.gain_db} dB${s.note ? ' (' + s.note + ')' : ''}`).join('; '));
    const d = [t.demo.mp4 && `[16:9](${t.demo.mp4})`, t.demo.mp4_9x16 && `[9:16](${t.demo.mp4_9x16})`, t.demo.stills && `[stills](${t.demo.stills})`].filter(Boolean);
    L.push(`- **Demo:** ${d.join(' / ') || 'not rendered yet'}`, '');
  }
  return L.join('\n');
}

const cat = catalog(), json = JSON.stringify(cat, null, 1) + '\n', R = path.join(ROOT, 'README.md'), C = path.join(ROOT, 'catalog.json');
const md = fs.readFileSync(R, 'utf8'), a = md.indexOf('<!-- BEGIN CATALOG -->'), b = md.indexOf('<!-- END CATALOG -->');
if (a < 0 || b < 0) { console.error('README markers missing'); process.exit(2); }
const md2 = md.slice(0, a) + '<!-- BEGIN CATALOG -->\n' + readme(cat) + '\n' + md.slice(b);
if (process.argv.includes('--check')) {
  const stale = [(fs.existsSync(C) ? fs.readFileSync(C, 'utf8') : '') !== json && 'catalog.json', md !== md2 && 'README.md'].filter(Boolean);
  if (stale.length) { console.error('stale: ' + stale.join(', ') + ' (run node tools/build.mjs)'); process.exit(1); }
  console.log('catalog + README up to date'); process.exit(0);
}
fs.writeFileSync(C, json); fs.writeFileSync(R, md2);
// aliases.json: every accepted 'transitions/<name>' -> registry key + params + kind (for Python: tools/check_ids.py, planners)
const AL = path.join(ROOT, 'aliases.json');
fs.writeFileSync(AL, JSON.stringify({ note: 'GENERATED by tools/build.mjs from lib/ids.js', aliases: Object.fromEntries(Object.keys(ALIASES).sort().map(k => [k, resolveTx(k)])) }, null, 1) + '\n');
console.log(`wrote catalog.json (${cat.transitions.length} transitions) + README catalog section`);
