#!/usr/bin/env python3
"""Render the music kit -> music/library/{beds,stingers,logos}/*.wav (48 kHz 24-bit stereo) + music/manifest.json + music/tempo_maps.json + per-bed .json (events in frames).
usage: python3 build_music.py [--fps 30] [--only substring] [--no-wav]
Everything is generated by code (compose.py / stingers.py / logo.py, owned synthesis). Beds are mastered to -16 LUFS-I (stand-alone preview level; the mixer sets the real level),
true peak <= -1.5 dBTP. Loop beds are seamless (ring-out tails folded onto the head)."""
import json
import os
import sys
import time
import numpy as np
import soundfile as sf
import _path  # noqa: F401
from mpaudio import dsp, meter
from mpaudio.dsp import SR
import compose as C
import grid
import logo as L
import stingers as ST
import mixer
from presets import PRESETS

HERE = os.path.dirname(os.path.abspath(__file__))
BED_LUFS = -16.0

# structured demo beds (non-loop): (preset, structure, name)
STRUCTURED = [("tech_pulse", "ad_30s", "bed_tech_pulse_ad30"), ("hype_house", "reel_15s", "bed_hype_house_reel15"), ("cinematic_drone", "cine_30s", "bed_cinematic_drone_cine30"),
              ("playful_bounce", "hook_6s", "bed_playful_bounce_hook6"),
              # 2026-10-13 expansion: tempo ramp + the new structures
              ("anthem_ramp", "anthem_ramp_16", "bed_anthem_ramp16"), ("corporate_bright", "explainer_60s", "bed_corporate_bright_explainer60"),
              ("chiptune_8bit", "cold_open_3s", "bed_chiptune_cold_open3"), ("orchestral_synth_epic", "outro_8s", "bed_orchestral_epic_outro8"),
              ("comedy_pizzicato", "sting_only", "bed_comedy_pizzicato_sting")]
NO_LOOP = {"anthem_ramp"}                 # a tempo ramp cannot be a seamless loop
# tabla thekas and the bhangra chaal (music/theka.py): (name, kind, arg, cycles/bars, mood, use, desc)
THEKA_BEDS = [("bed_tabla_teental_loop", "theka", "teental", 2, ["calm", "warm"], ["short_film", "talking_head", "ad"], "tabla teental theka (16 matras x 2 cycles) over a tanpura; sam / khali frames in the sidecar"),
              ("bed_tabla_keherwa_loop", "theka", "keherwa", 4, ["warm", "playful"], ["ad", "talking_head", "mime"], "tabla keherwa theka (8 matras x 4 cycles) over a tanpura; the everyday light-music groove"),
              ("bed_tabla_dadra_loop", "theka", "dadra", 6, ["warm", "playful"], ["ad", "short_film", "mime"], "tabla dadra theka (6 matras x 6 cycles) over a tanpura; lilting 6-beat feel"),
              ("bed_bhangra_dhol_loop", "bhangra", None, 8, ["hype", "festive"], ["ad", "beat_edit", "mime"], "bhangra dhol chaal (12/8 feel, own dhol voices) with a high plucked riff")]
SITAR_LOGOS = [("logo_sitar_orbit", "Orbit", None), ("logo_sitar_nova", "Nova", None), ("logo_sitar_pattern_ascend_land", None, "ascend_land")]
EVENT_KICKS = ("kick", "kick_soft", "dhol", "808", "t_dha", "t_ge", "t_dhin", "dholak_dha", "dholak_ge", "taiko", "nagara", "chip_kick")
BRANDS = ["Orbit", "Nova", "Lumen", "Atlas", "Ember"]   # fictional example brands


def stats(y, extra):
    d = {"lufs_i": round(meter.lufs_integrated(y), 2), "true_peak_db": round(meter.true_peak_db(y), 2), "sample_peak_db": round(meter.sample_peak_db(y), 2), "lufs_s_max": round(meter.lufs_short_max(y), 2),
         "centroid_hz": round(meter.centroid_hz(y)), "crest_db": round(meter.crest_db(y), 1), "duration_s": round(len(y) / SR, 3)}
    d.update(extra)
    return d


def write(path, y):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    sf.write(path, y.astype(np.float32), SR, subtype="PCM_24")


def build(fps=30, only=None, write_wav=True):
    t0 = time.time()
    items = []
    # ---- beds: 8-bar seamless loops for every preset
    jobs = [(p, "loop_8", "bed_%s_loop8" % p) for p in PRESETS if p not in NO_LOOP] + STRUCTURED
    for preset, struct, name in jobs:
        if only and only not in name:
            continue
        r = C.compose(preset, struct, seed=1 + len(name) % 7, fps=fps)
        y, G, g = mixer.master(r["mix"], BED_LUFS, -1.5)
        meta = r["meta"]
        tm = grid.tempo_map(meta["bpm"], fps, meta["bars"])
        drop = [e["frame"] for e in r["events"] if e["kind"] in ("drop", "hook_hit")]
        rel = os.path.join("library", "beds", name + ".wav")
        if write_wav:
            write(os.path.join(HERE, rel), y)
        side = {"meta": meta, "tempo": {k: tm[k] for k in ("bpm", "frames_per_beat", "frames_per_bar", "beat_seconds", "bar_seconds", "snap_error_pct")}, "drop_frames": drop,
                "kick_frames": [e["frame"] for e in r["events"] if e["kind"] in EVENT_KICKS], "clap_snare_frames": [e["frame"] for e in r["events"] if e["kind"] in ("clap", "snare")],
                "riser_frames": [e["frame"] for e in r["events"] if e["kind"] == "riser"], "bar_frames": tm["bar_frames"], "beat_frames": tm["beat_frames"]}
        if write_wav:
            json.dump(side, open(os.path.join(HERE, "library", "beds", name + ".json"), "w"))
        items.append({"id": "music." + name, "kind": "bed", "file": rel, "preset": preset, "structure": struct, "loop": meta["loop"], "fps": fps, "bpm": meta["bpm"], "bpm_requested": meta["bpm_requested"],
                      "frames_per_beat": meta["frames_per_beat"], "bars": meta["bars"], "key": "A" if meta["key_midi"] % 12 == 9 else str(meta["key_midi"] % 12), "scale": meta["scale"],
                      "mood": PRESETS[preset]["mood"], "use": PRESETS[preset]["use"], "desc": PRESETS[preset]["desc"], "sections": meta["sections"], "drop_frames": drop, "sidecar": rel[:-4] + ".json",
                      "tags": ["family:music", "bed", "preset:" + preset] + ["mood:" + m for m in PRESETS[preset]["mood"]] + ["use:" + u for u in PRESETS[preset]["use"]] + (["loop"] if meta["loop"] else []),
                      **stats(y, {"mastered_lufs": BED_LUFS})})
        if meta.get("tempo_ramp"):
            items[-1]["tempo_ramp"] = meta["tempo_ramp"]
            items[-1]["tags"].append("tempo-ramp")
            side["tempo_ramp"] = meta["tempo_ramp"]
            rm = grid.tempo_ramp_map(meta["tempo_ramp"]["bpm_from"], meta["tempo_ramp"]["bpm_to"], fps, meta["bars"])
            side["bar_frames"], side["beat_frames"] = rm["bar_frames"], rm["beat_frames"]
            if write_wav:
                json.dump(side, open(os.path.join(HERE, "library", "beds", name + ".json"), "w"))
    # ---- tabla thekas + bhangra chaal (frame-exact matras, seamless)
    import theka as TK
    for name, kind, arg, cyc, mood, use, desc in THEKA_BEDS:
        if only and only not in name:
            continue
        r = TK.render_theka(arg, fps, cyc, seed=3) if kind == "theka" else TK.render_bhangra(fps, cyc, seed=3)
        y, G, g = mixer.master(r["mix"], BED_LUFS, -1.5)
        meta = r["meta"]
        rel = os.path.join("library", "beds", name + ".wav")
        if write_wav:
            write(os.path.join(HERE, rel), y)
        fpb = meta["frames_per_beat"]
        nb = meta.get("matras", 4)
        side = {"meta": meta, "tempo": {"bpm": meta["bpm"], "frames_per_beat": fpb, "frames_per_cycle": fpb * nb, "beat_seconds": round(fpb / fps, 5)},
                "beat_frames": [i * fpb for i in range(meta["length_frames"] // fpb)], "bar_frames": [i * fpb * nb for i in range(meta["length_frames"] // (fpb * nb))],
                "sam_frames": [e["frame"] for e in r["events"] if e.get("sam")], "khali_frames": [e["frame"] for e in r["events"] if e.get("khali")],
                "kick_frames": [e["frame"] for e in r["events"] if e["kind"] == "dhol" or e.get("bol") in ("dha", "dhin")], "drop_frames": [], "riser_frames": [], "clap_snare_frames": []}
        if write_wav:
            json.dump(side, open(os.path.join(HERE, "library", "beds", name + ".json"), "w"))
        items.append({"id": "music." + name, "kind": "bed", "file": rel, "preset": meta["preset"], "structure": meta["structure"], "loop": True, "fps": fps, "bpm": meta["bpm"],
                      "bpm_requested": meta["bpm_requested"], "frames_per_beat": fpb, "bars": meta["bars"], "key": "A", "scale": meta["scale"], "mood": mood, "use": use, "desc": desc,
                      "sections": meta["sections"], "drop_frames": [], "sidecar": rel[:-4] + ".json", "tala": meta.get("tala"), "matras": nb,
                      "tags": ["family:music", "bed", "loop", "region:in", "preset:" + meta["preset"]] + ["mood:" + m for m in mood] + ["use:" + u for u in use],
                      **stats(y, {"mastered_lufs": BED_LUFS})})
    # ---- stingers
    for sid, fn in ST.STINGERS.items():
        name = "sting_" + sid
        if only and only not in name:
            continue
        y, anchor, info = fn(7)
        y = np.stack([dsp.fft_filter(y[:, 0], 25.0, None, 2), dsp.fft_filter(y[:, 1], 25.0, None, 2)], 1)
        y = y * dsp.db(-3.0 - meter.true_peak_db(y))
        n0 = np.nonzero(np.max(np.abs(y), axis=1) > 1e-4)[0]
        a0 = max(0, n0[0] - dsp.ms(1.5))
        y, anchor = y[a0:], anchor - a0
        nz = np.nonzero(np.max(np.abs(y), axis=1) > 10 ** (-66 / 20) * 0.7)[0]
        y = dsp.fade_out(y[:nz[-1] + 1], dsp.ms(40))
        y = dsp.fade_in(y, dsp.ms(1))
        rel = os.path.join("library", "stingers", name + ".wav")
        if write_wav:
            write(os.path.join(HERE, rel), y)
        items.append({"id": "music." + name, "kind": "stinger", "file": rel, "anchor_sample": int(anchor), "anchor_ms": round(anchor / SR * 1000, 1), "key": "A", "info": info,
                      "anchor_frame_offset": -1 if info.get("riser_end_frame_offset") else 0, "tags": ["family:music", "stinger", "key:A", "anchor:" + ("end" if info.get("riser_end_frame_offset") else "start")],
                      "desc": "musical stinger in A: " + sid.replace("_", " "), **stats(y, {})})
    # ---- logos
    for pat in ("ascend_land", "fifth_lift", "question", "pulse_pad", "two_note", "drop_land"):
        name = "logo_pattern_" + pat
        if only and only not in name:
            continue
        y, anchor, info = L.render_logo(pattern=pat, seed=3)
        items.append(_logo_item(name, y, anchor, info, write_wav))
    for b in BRANDS:
        name = "logo_brand_" + b.lower()
        if only and only not in name:
            continue
        y, anchor, info = L.render_logo(name=b, seed=3)
        items.append(_logo_item(name, y, anchor, info, write_wav))
    for name, brand, pat in SITAR_LOGOS:
        if only and only not in name:
            continue
        y, anchor, info = L.render_logo_sitar(name=brand, pattern=pat, seed=3)
        it = _logo_item(name, y, anchor, info, write_wav)
        it["desc"] = "sitar-and-tanpura sonic logo: " + (brand or pat)
        it["tags"] = it["tags"] + ["region:in", "timbre:sitar"]
        items.append(it)
    man = {"version": 1, "sample_rate": SR, "bit_depth": 24, "fps_default": fps, "bed_lufs_i": BED_LUFS, "count": len(items), "built_s": round(time.time() - t0, 1), "items": items,
           "notes": "All generated by code. Beds are mastered to -16 LUFS-I as a stand-alone preview level; the mixer sets the real level. Loop beds are seamless. anchor_sample on stingers/logos lands on (visual frame + 1) x SR/fps."}
    if not only:
        json.dump({k: v for k, v in man.items() if k != "built_s"}, open(os.path.join(HERE, "manifest.json"), "w"), indent=1)   # no wall-clock field: a rebuild leaves the manifest byte-identical
        grid.write_tempo_maps(os.path.join(HERE, "tempo_maps.json"))
    return man


def _logo_item(name, y, anchor, info, write_wav):
    y = np.stack([dsp.fft_filter(y[:, 0], 25.0, None, 2), dsp.fft_filter(y[:, 1], 25.0, None, 2)], 1)
    y = y * dsp.db(-3.0 - meter.true_peak_db(y))
    nz = np.nonzero(np.max(np.abs(y), axis=1) > 10 ** (-66 / 20) * 0.7)[0]
    a0 = max(0, nz[0] - dsp.ms(1.5))
    y, anchor = y[a0:nz[-1] + 1], anchor - a0
    y = dsp.fade_out(dsp.fade_in(y, dsp.ms(1)), dsp.ms(40))
    rel = os.path.join("library", "logos", name + ".wav")
    if write_wav:
        write(os.path.join(HERE, rel), y)
    return {"id": "music." + name, "kind": "logo", "file": rel, "anchor_sample": int(anchor), "anchor_ms": round(anchor / SR * 1000, 1), "key": "A", "info": info,
            "anchor_frame_offset": 0, "tags": ["family:music", "logo", "key:A", "anchor:crest"], "desc": "sonic logo: " + (info.get("name") or info.get("pattern", "")), **stats(y, {})}


if __name__ == "__main__":
    fps = int(sys.argv[sys.argv.index("--fps") + 1]) if "--fps" in sys.argv else 30
    only = sys.argv[sys.argv.index("--only") + 1] if "--only" in sys.argv else None
    m = build(fps, only, "--no-wav" not in sys.argv)
    print("rendered", m["count"], "items in", m["built_s"], "s")
